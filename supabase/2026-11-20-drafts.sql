create table if not exists public.drafts (
  id           bigint generated by default as identity primary key,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  created_by   text not null default '',
  label        text not null default '',
  client_name  text not null default '',
  bhk          integer,
  carpet_area  numeric not null default 0,
  tier         text not null default '',
  total        numeric not null default 0,
  data         jsonb not null   -- everything needed to continue: size, scope, quantities, finish, agreed rates, details
);

alter table public.drafts enable row level security;
drop policy if exists "staff full access" on public.drafts;
create policy "staff full access" on public.drafts for all to authenticated using (true) with check (true);
grant select, insert, update, delete on public.drafts to authenticated, service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;
revoke all on public.drafts from anon;
