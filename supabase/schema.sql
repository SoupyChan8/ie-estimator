-- Interior Editors estimator — Supabase database setup.
-- Paste this whole file into Supabase → SQL Editor → New query → Run. Safe to run again.

-- ───────────────────────── Rate book ─────────────────────────

create table if not exists public.categories (
  id          bigint generated by default as identity primary key,
  name        text    not null,
  sort_order  integer not null default 0
);

create table if not exists public.items (
  id                bigint generated by default as identity primary key,
  category_id       bigint  not null references public.categories (id) on delete cascade,
  -- set for a nested add-on (e.g. Puja Unit under TV Unit); one level only
  parent_id         bigint  references public.items (id) on delete cascade,
  name              text    not null,
  description       text    not null default '',
  unit              text    not null default 'sqft' check (unit in ('sqft', 'rft', 'nos', 'lumpsum')),
  rate_standard     numeric not null default 0 check (rate_standard >= 0),
  rate_premium      numeric check (rate_premium >= 0),   -- blank = same as Standard
  rate_luxury       numeric check (rate_luxury >= 0),    -- blank = same as Standard
  qty_bhk1          numeric not null default 0,
  qty_bhk2          numeric not null default 0,
  qty_bhk3          numeric not null default 0,
  qty_bhk4          numeric not null default 0,
  -- on: quantity = the client's carpet area; the BHK columns are just 1 (included) or 0
  scales_with_area  boolean not null default false,
  active            boolean not null default true,
  sort_order        integer not null default 0
);
create index if not exists items_category_idx on public.items (category_id);
create index if not exists items_parent_idx on public.items (parent_id);

-- ───────────────────────── Contracts ─────────────────────────

create sequence if not exists public.quotation_seq start 154;

create table if not exists public.contracts (
  id                  bigint generated by default as identity primary key,
  quotation_no        text unique,
  created_at          timestamptz not null default now(),
  created_by          text not null default '',
  client_name         text not null,
  client_phone        text not null default '',
  client_email        text not null default '',
  site_address        text not null default '',
  project_scope       text not null default '',
  bhk                 integer not null check (bhk between 1 and 4),
  carpet_area         numeric not null default 0,
  tier                text not null check (tier in ('standard', 'premium', 'luxury')),
  total               numeric not null default 0,
  designer_name       text not null default '',
  line_items          jsonb not null default '[]'::jsonb,
  client_signature    text not null default '',   -- PNG data URL
  designer_signature  text not null default '',   -- PNG data URL
  pdf_path            text not null default '',   -- file in the "quotations" storage bucket
  pdf_url             text not null default '',   -- older PDFs saved on Google Drive
  pdf_options         jsonb                        -- studio edits for the PDF; null = defaults
);

-- Quotation numbers like IE-2026-154, given out by the database so two iPads never clash.
create or replace function public.set_quotation_no() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.quotation_no is null or new.quotation_no = '' then
    new.quotation_no := 'IE-' || extract(year from now())::int || '-' || nextval('public.quotation_seq');
  end if;
  return new;
end $$;

drop trigger if exists contracts_quotation_no on public.contracts;
create trigger contracts_quotation_no before insert on public.contracts
  for each row execute function public.set_quotation_no();

-- ───────────────────────── Saved versions & settings ─────────────────────────

create table if not exists public.versions (
  id          bigint generated by default as identity primary key,
  kind        text not null check (kind in ('ratebook', 'terms')),
  name        text not null,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  created_by  text not null default '',
  summary     text not null default '',
  data        jsonb not null,
  hash        text   -- rate book fingerprint, so the app can tell which version is in use
);

-- default_terms_version, active_ratebook_version
create table if not exists public.settings (
  key    text primary key,
  value  text
);

-- ───────────────────────── Functions the app calls ─────────────────────────

-- Replaces the whole rate book in one go (used when switching to a saved version).
create or replace function public.replace_rate_book(book jsonb) returns void
language plpgsql security definer set search_path = public as $$
begin
  delete from public.items where true;
  delete from public.categories where true;
  insert into public.categories (id, name, sort_order)
    select (c->>'id')::bigint, c->>'name', coalesce((c->>'sortOrder')::int, 0)
    from jsonb_array_elements(book->'categories') c;
  -- main items first, then add-ons (they point at a main item)
  insert into public.items (id, category_id, parent_id, name, description, unit, rate_standard, rate_premium,
                            rate_luxury, qty_bhk1, qty_bhk2, qty_bhk3, qty_bhk4, scales_with_area, active, sort_order)
    select (i->>'id')::bigint, (i->>'categoryId')::bigint, nullif(i->>'parentId', '')::bigint, i->>'name',
           coalesce(i->>'description', ''), coalesce(i->>'unit', 'sqft'), coalesce((i->>'rateStandard')::numeric, 0),
           nullif(i->>'ratePremium', '')::numeric, nullif(i->>'rateLuxury', '')::numeric,
           coalesce((i->>'qtyBhk1')::numeric, 0), coalesce((i->>'qtyBhk2')::numeric, 0),
           coalesce((i->>'qtyBhk3')::numeric, 0), coalesce((i->>'qtyBhk4')::numeric, 0),
           coalesce((i->>'scalesWithArea')::boolean, false), coalesce((i->>'active')::boolean, true),
           coalesce((i->>'sortOrder')::int, 0)
    from jsonb_array_elements(book->'items') i
    order by (i->>'parentId') is not null;
  perform public.sync_sequences();
end $$;

-- After rows are inserted with their own ids (restore / import), make new ids continue after the highest one.
create or replace function public.sync_sequences() returns void
language plpgsql security definer set search_path = public as $$
begin
  perform setval(pg_get_serial_sequence('public.categories', 'id'), greatest(coalesce((select max(id) from public.categories), 0), 1));
  perform setval(pg_get_serial_sequence('public.items', 'id'), greatest(coalesce((select max(id) from public.items), 0), 1));
  perform setval(pg_get_serial_sequence('public.contracts', 'id'), greatest(coalesce((select max(id) from public.contracts), 0), 1));
  perform setval(pg_get_serial_sequence('public.versions', 'id'), greatest(coalesce((select max(id) from public.versions), 0), 1));
end $$;

-- Sets the next quotation number (used once when moving over from Google Sheets).
create or replace function public.set_next_quotation_no(n bigint) returns void
language sql security definer set search_path = public as $$
  select setval('public.quotation_seq', greatest(n, 1), false);
$$;

-- ───────────────────────── Security: only signed-in staff ─────────────────────────
-- Sign-ups are turned off in the dashboard, so "authenticated" means an account you created.

alter table public.categories enable row level security;
alter table public.items      enable row level security;
alter table public.contracts  enable row level security;
alter table public.versions   enable row level security;
alter table public.settings   enable row level security;

do $$
declare t text;
begin
  foreach t in array array['categories', 'items', 'contracts', 'versions', 'settings'] loop
    execute format('drop policy if exists "staff full access" on public.%I', t);
    execute format('create policy "staff full access" on public.%I for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- The Data API only sees tables it's been granted (automatic grants are off for this project).
grant usage on schema public to authenticated, service_role;
grant select, insert, update, delete on public.categories, public.items, public.contracts, public.versions, public.settings
  to authenticated, service_role;
grant usage, select on all sequences in schema public to authenticated, service_role;
revoke all on public.categories, public.items, public.contracts, public.versions, public.settings from anon;

revoke all on function public.replace_rate_book(jsonb) from public, anon;
revoke all on function public.sync_sequences() from public, anon;
revoke all on function public.set_next_quotation_no(bigint) from public, anon;
grant execute on function public.replace_rate_book(jsonb) to authenticated, service_role;
grant execute on function public.sync_sequences() to authenticated, service_role;
grant execute on function public.set_next_quotation_no(bigint) to authenticated, service_role;
grant usage, select on sequence public.quotation_seq to authenticated, service_role;

-- ───────────────────────── PDF storage ─────────────────────────

insert into storage.buckets (id, name, public)
values ('quotations', 'quotations', false)
on conflict (id) do nothing;

drop policy if exists "staff read quotations" on storage.objects;
drop policy if exists "staff write quotations" on storage.objects;
drop policy if exists "staff update quotations" on storage.objects;
drop policy if exists "staff delete quotations" on storage.objects;
create policy "staff read quotations" on storage.objects for select to authenticated using (bucket_id = 'quotations');
create policy "staff write quotations" on storage.objects for insert to authenticated with check (bucket_id = 'quotations');
create policy "staff update quotations" on storage.objects for update to authenticated using (bucket_id = 'quotations');
create policy "staff delete quotations" on storage.objects for delete to authenticated using (bucket_id = 'quotations');
